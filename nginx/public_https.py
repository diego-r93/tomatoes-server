"""Issue and renew the portal certificate using Cloudflare DNS-01 only."""
import hashlib
import logging
import os
from pathlib import Path
import re
import subprocess
import time

LOG = logging.getLogger("public-https")


def domain_name(value):
    value = value.strip().lower()
    if len(value) > 253 or not re.fullmatch(r"(?:[a-z0-9](?:[a-z0-9-]{0,61}[a-z0-9])?\.)+[a-z]{2,63}", value):
        raise ValueError("PUBLIC_HTTPS_DOMAIN must be a DNS hostname")
    return value


def certbot_command(env, credentials):
    domain = domain_name(env.get("PUBLIC_HTTPS_DOMAIN", ""))
    email = env.get("ACME_EMAIL", "").strip()
    if not re.fullmatch(r"[^\s@]+@[^\s@]+\.[^\s@]+", email):
        raise ValueError("Set ACME_EMAIL in .env")
    if not env.get("CLOUDFLARE_DNS_API_TOKEN", "").strip():
        raise ValueError("Set CLOUDFLARE_DNS_API_TOKEN in .env")
    staging = env.get("ACME_STAGING", "false").lower() == "true"
    config_dir = "/etc/letsencrypt/staging" if staging else "/etc/letsencrypt"
    command = ["certbot", "certonly", "--non-interactive", "--agree-tos", "--email", email,
               "--dns-cloudflare", "--dns-cloudflare-credentials", str(credentials),
               "--dns-cloudflare-propagation-seconds", "60", "--cert-name", "portal",
               "--domain", domain, "--key-type", "ecdsa", "--elliptic-curve", "secp256r1",
               "--keep-until-expiring", "--config-dir", config_dir,
               "--work-dir", "/var/lib/letsencrypt", "--logs-dir", "/var/log/letsencrypt"]
    if staging:
        command.append("--staging")
    return domain, command


def server_config(domain, generation):
    domain_name(domain)
    if not re.fullmatch(r"[a-f0-9]{16}", generation):
        raise ValueError("Invalid certificate generation")
    base = "/etc/nginx/tls/public/versions/" + generation
    return ("# Generated by the public HTTPS certificate service.\n"
            "server {\n    listen 443 ssl;\n    server_name " + domain + ";\n"
            "    ssl_certificate " + base + "/fullchain.pem;\n"
            "    ssl_certificate_key " + base + "/privkey.pem;\n"
            "    ssl_protocols TLSv1.2 TLSv1.3;\n"
            '    add_header Strict-Transport-Security "max-age=86400" always;\n'
            "    include /etc/nginx/portal-locations.conf;\n}\n")


def atomic_write(path, content, mode):
    temporary = path.with_name("." + path.name + ".tmp")
    descriptor = os.open(temporary, os.O_WRONLY | os.O_CREAT | os.O_TRUNC, mode)
    try:
        with os.fdopen(descriptor, "wb") as target:
            target.write(content)
        os.chmod(temporary, mode)
        os.replace(temporary, path)
    finally:
        temporary.unlink(missing_ok=True)


def publish_certificate(domain, source=Path("/etc/letsencrypt/live/portal"), target=Path("/public")):
    from cryptography import x509
    from cryptography.hazmat.primitives import serialization
    from cryptography.hazmat.primitives.serialization import Encoding, PublicFormat
    from datetime import datetime, timezone

    chain = (source / "fullchain.pem").read_bytes()
    key_data = (source / "privkey.pem").read_bytes()
    cert = x509.load_pem_x509_certificate(chain)
    names = cert.extensions.get_extension_for_class(x509.SubjectAlternativeName).value.get_values_for_type(x509.DNSName)
    if domain not in names or cert.not_valid_after_utc <= datetime.now(timezone.utc):
        raise ValueError("Certificate hostname or expiration is invalid")
    key = serialization.load_pem_private_key(key_data, password=None)
    if key.public_key().public_bytes(Encoding.DER, PublicFormat.SubjectPublicKeyInfo) != cert.public_key().public_bytes(Encoding.DER, PublicFormat.SubjectPublicKeyInfo):
        raise ValueError("Certificate and private key do not match")
    generation = hashlib.sha256(chain).hexdigest()[:16]
    version = target / "versions" / generation
    version.mkdir(parents=True, exist_ok=True, mode=0o700)
    atomic_write(version / "fullchain.pem", chain, 0o644)
    atomic_write(version / "privkey.pem", key_data, 0o600)
    config = server_config(domain, generation).encode()
    config_path = target / "server.conf"
    if not config_path.exists() or config_path.read_bytes() != config:
        atomic_write(config_path, config, 0o600)
        LOG.info("Public certificate ready for %s; Nginx will reload automatically", domain)


def issue_once(env):
    credentials = Path("/run/acme/cloudflare.ini")
    domain, command = certbot_command(env, credentials)
    token = env["CLOUDFLARE_DNS_API_TOKEN"].strip()
    if any(character.isspace() for character in token) or any(character in token for character in "\r\n"):
        raise ValueError("Invalid Cloudflare token format")
    credentials.parent.mkdir(parents=True, exist_ok=True, mode=0o700)
    atomic_write(credentials, ("dns_cloudflare_api_token = " + token + "\n").encode(), 0o600)
    LOG.info("Checking the certificate for %s through Cloudflare DNS-01", domain)
    # Certbot's private logs are kept in the ACME volume; never print credentials.
    try:
        result = subprocess.run(command, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL, timeout=600)
    finally:
        credentials.unlink(missing_ok=True)
    if result.returncode:
        LOG.error("Certificate issuance/renewal failed; inspect the private ACME log")
        return False
    if env.get("ACME_STAGING", "false").lower() != "true":
        publish_certificate(domain)
        LOG.info("Production certificate check completed successfully")
    else:
        LOG.info("ACME staging validation passed; no test certificate was installed")
    return True


def main():
    os.umask(0o077)
    enabled = os.getenv("PUBLIC_HTTPS_ENABLED", "false").lower()
    if enabled != "true":
        LOG.info("Public HTTPS certificate service is disabled")
        while True:
            time.sleep(3600)
    while True:
        try:
            success = issue_once(os.environ)
        except Exception as issue:
            # Exceptions from API clients may contain credentials; only print the type.
            LOG.error("Certificate service failed (%s); existing certificates were preserved", type(issue).__name__)
            success = False
        time.sleep(43200 if success else 3600)


if __name__ == "__main__":
    logging.basicConfig(level=logging.INFO, format="%(levelname)s %(name)s %(message)s")
    main()
